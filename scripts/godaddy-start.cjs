const {randomBytes}=require('node:crypto');
const {startReportScheduler}=require('./report-scheduler.cjs');
const {startAppointmentScheduler}=require('./appointment-scheduler.cjs');
const { spawn } = require('node:child_process');
const { ROOT, loadEnvironment, databaseUrl } = require('./database-config.cjs');
const {siteRole,validateDeployment,runsSchedulers}=require('./site-deployment.cjs');
function main() {
  const development = process.argv.includes('--dev');
  process.env.NODE_ENV = development ? 'development' : 'production';
  loadEnvironment();
  validateDeployment();
  if(siteRole()!=='sales')process.env.DATABASE_URL = databaseUrl();
  let child;
  let stopScheduler=()=>{};
  // This private per-process credential is generated by GroomPro, never entered by a tenant.
  process.env.GROOMPRO_SCHEDULER_TOKEN=development?'':randomBytes(32).toString('hex');
  let stopping = false;
  for (const signal of ['SIGTERM', 'SIGINT']) process.on(signal, () => {
    stopping = true;
    stopScheduler();
    if (child) child.kill(signal);
  });
  function launch(args, done) {
    child = spawn(process.execPath, args, { cwd: ROOT, stdio: 'inherit', env: process.env });
    child.on('error', () => { stopScheduler();console.error('GroomPro: unable to launch runtime.'); process.exitCode = 1; });
    child.on('exit', (code, signal) => {
      stopScheduler();
      if (stopping || signal) { process.exitCode = 1; return; }
      done(code ?? 1);
    });
  }
  const serve = code => {
    if (code !== 0) { process.exitCode = code; return; }
    launch([require.resolve('next/dist/bin/next'), development ? 'dev' : 'start', '-H', '0.0.0.0', '-p', process.env.PORT || '3000'], code => { stopScheduler();process.exitCode = code; });
    if(!development&&runsSchedulers()){const options={port:process.env.PORT||'3000',token:process.env.GROOMPRO_SCHEDULER_TOKEN},stopMessages=startAppointmentScheduler(options),stopReports=startReportScheduler(options);stopScheduler=()=>{stopMessages();stopReports();};}
  };
  const startSite = code => {
    if (code !== 0 || development) return serve(code);
    launch([require.resolve('./prepare-production.cjs')], serve);
  };
  if(['sales','admin'].includes(siteRole()))startSite(0);
  else launch([require.resolve('./bootstrap-godaddy.cjs')], startSite);
}
if (require.main === module) {
  require('./prepare-production.cjs').waitForInstall().then(main).catch(error => { console.error(error.message); process.exitCode = 1; });
}
module.exports = { main };
