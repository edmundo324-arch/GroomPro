const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { ROOT } = require('./database-config.cjs');
// Historical migrations are not a from-empty chain. Extract only supplemental
// CREATEs; core columns and enum values belong to schema.prisma.
const supplements = ['20260908_pricing_history', '20260910_customer_accounts_rewards',
  '20260910_memberships_documents_rebooking', '20260913_booking_assets', '20260914_employee_schedules'];
function buildSchema() {
  const result = spawnSync(process.execPath, [require.resolve('prisma/build/index.js'),
    'migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/schema.prisma', '--script'],
    { cwd: ROOT, encoding: 'utf8', env: { ...process.env, DATABASE_URL: 'mysql://build:build@localhost:3306/build' } });
  if (result.error || result.status !== 0) throw new Error('Unable to generate Prisma SQL schema.');
  let sql = '-- GroomPro: import into an EMPTY selected MySQL database only.\n'
    + '-- Generated by npm run db:sql; bootstrap uses this same schema.\n\n' + result.stdout;
  for (const name of supplements) {
    const source = fs.readFileSync(path.join(ROOT, 'prisma/migrations', name, 'migration.sql'), 'utf8');
    const creates = source.match(/CREATE TABLE(?: IF NOT EXISTS)? `[\s\S]*?;/g);
    if (!creates?.length) throw new Error(`No supplemental tables in ${name}.`);
    sql += '\n' + creates.join('\n\n') + '\n';
  }
  // No demo customers, appointments or employee PINs are installed at startup.
  sql += '\n' + fs.readFileSync(path.join(ROOT, 'prisma/migrations/20260909_seed_feature_modules/migration.sql'), 'utf8');
  fs.writeFileSync(path.join(ROOT, 'godaddy-groompro-schema.sql'), sql);
  const { schemaPlan } = require('./bootstrap-godaddy.cjs');
  fs.writeFileSync(path.join(ROOT, 'godaddy-groompro-schema.json'), JSON.stringify(schemaPlan(sql).tables.map(t => ({ name: t.name, columns: t.columns.map(c => c.name) })), null, 2) + '\n');
  console.log('Created godaddy-groompro-schema.sql');
  return sql;
}
if (require.main === module) buildSchema();
module.exports = { buildSchema };
